SELECT gen_random_uuid(), d.id, s."Id", 1,
       round(d.base * (0.9 + (abs(hashtext(d.id::text || s."Id"::text)) % 31) / 100.0), 1),
       now() - ((1 + abs(hashtext(s."Id"::text || d.id::text)) % 40) * interval '1 hour')
FROM _seed_drug d CROSS JOIN "DrugStore" s
WHERE d.name <> 'Препарат без предложений'
